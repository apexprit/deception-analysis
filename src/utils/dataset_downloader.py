    def load_dataset(self, dataset_id: str, 
                    split: Optional[str] = None) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """Load a downloaded dataset.
        
        Args:
            dataset_id: Dataset identifier
            split: Optional split to load ('train', 'test', 'val')
            
        Returns:
            Tuple of (features DataFrame, labels DataFrame)
        """
        dataset_dir = self.data_dir / dataset_id
        
        if not dataset_dir.exists():
            raise FileNotFoundError(f"Dataset '{dataset_id}' not found. Download it first.")
        
        # Check for synthetic dataset
        if dataset_id == "synthetic_demo":
            features_path = dataset_dir / "synthetic_deception_features.csv"
            labels_path = dataset_dir / "synthetic_deception_labels.csv"
            
            if not features_path.exists():
                # Generate if not exists
                self._generate_synthetic_dataset(dataset_dir)
            
            features = pd.read_csv(features_path)
            labels_df = pd.read_csv(labels_path)
            
            return features, labels_df
        
        # For real datasets, look for common file patterns
        csv_files = list(dataset_dir.glob("*.csv"))
        
        if not csv_files:
            # Try to find data in subdirectories
            for root, dirs, files in os.walk(dataset_dir):
                for file in files:
                    if file.endswith('.csv'):
                        csv_files.append(Path(root) / file)
        
        if not csv_files:
            raise FileNotFoundError(f"No CSV files found in {dataset_dir}")
        
        # Try to identify features and labels files
        features_file = None
        labels_file = None
        
        for csv_file in csv_files:
            name = csv_file.stem.lower()
            if 'feature' in name or 'data' in name or 'X' in name:
                features_file = csv_file
            elif 'label' in name or 'target' in name or 'y' in name:
                labels_file = csv_file
        
        # If only one file found, assume it contains both
        if features_file and not labels_file:
            df = pd.read_csv(features_file)
            # Try to find label column
            label_cols = [col for col in df.columns if 'label' in col.lower() or 'target' in col.lower()]
            if label_cols:
                labels = df[label_cols]
                features = df.drop(columns=label_cols)
                return features, labels
            else:
                raise ValueError(f"Could not identify label column in {features_file}")
        
        # Load separate files
        if features_file and labels_file:
            features = pd.read_csv(features_file)
            labels = pd.read_csv(labels_file)
            return features, labels
        
        # Fallback: use first CSV as features, assume no labels
        print(f"Warning: Could not identify label file, using {csv_files[0]} as features only")
        features = pd.read_csv(csv_files[0])
        # Create dummy labels (all 0)
        labels = pd.DataFrame({'label': [0] * len(features)})
        
        return features, labels
    
    def prepare_training_data(self, dataset_id: str, 
                             test_size: float = 0.2,
                             val_size: float = 0.1,
                             random_state: int = 42) -> Dict[str, Tuple[pd.DataFrame, pd.DataFrame]]:
        """Prepare dataset for training with train/val/test splits.
        
        Args:
            dataset_id: Dataset identifier
            test_size: Proportion for test set
            val_size: Proportion for validation set (from training set)
            random_state: Random seed
            
        Returns:
            Dictionary with 'train', 'val', 'test' splits
        """
        from sklearn.model_selection import train_test_split
        
        features, labels_df = self.load_dataset(dataset_id)
        
        # Extract labels array
        if 'label' in labels_df.columns:
            labels = labels_df['label'].values
        else:
            # Assume first column is label
            labels = labels_df.iloc[:, 0].values
        
        # Split into train+val and test
        X_temp, X_test, y_temp, y_test = train_test_split(
            features, labels, test_size=test_size, random_state=random_state, stratify=labels
        )
        
        # Split train into train and val
        val_relative_size = val_size / (1 - test_size)
        X_train, X_val, y_train, y_val = train_test_split(
            X_temp, y_temp, test_size=val_relative_size, random_state=random_state, stratify=y_temp
        )
        
        # Convert back to DataFrames
        train_df = X_train.copy()
        train_df['label'] = y_train
        
        val_df = X_val.copy()
        val_df['label'] = y_val
        
        test_df = X_test.copy()
        test_df['label'] = y_test
        
        splits = {
            'train': (X_train, pd.DataFrame({'label': y_train})),
            'val': (X_val, pd.DataFrame({'label': y_val})),
            'test': (X_test, pd.DataFrame({'label': y_test}))
        }
        
        # Save splits
        dataset_dir = self.data_dir / dataset_id
        train_df.to_csv(dataset_dir / "train.csv", index=False)
        val_df.to_csv(dataset_dir / "val.csv", index=False)
        test_df.to_csv(dataset_dir / "test.csv", index=False)
        
        print(f"✅ Dataset split into: Train={len(X_train)}, Val={len(X_val)}, Test={len(X_test)}")
        
        return splits
    
    def get_dataset_info(self, dataset_id: str) -> Dict:
        """Get detailed information about a dataset.
        
        Args:
            dataset_id: Dataset identifier
            
        Returns:
            Dictionary with dataset information
        """
        if dataset_id not in self.PUBLIC_DATASETS:
            raise ValueError(f"Unknown dataset: {dataset_id}")
        
        dataset = self.PUBLIC_DATASETS[dataset_id]
        dataset_dir = self.data_dir / dataset_id
        
        info = {
            'id': dataset_id,
            'name': dataset.name,
            'description': dataset.description,
            'citation': dataset.citation,
            'features_available': dataset.features_available,
            'labels_available': dataset.labels_available,
            'subject_ids_available': dataset.subject_ids_available,
            'video_available': dataset.video_available,
            'audio_available': dataset.audio_available,
            'downloaded': dataset_dir.exists()
        }
        
        if dataset_dir.exists():
            # Count files
            files = list(dataset_dir.glob("*"))
            csv_files = list(dataset_dir.glob("*.csv"))
            
            info['local_path'] = str(dataset_dir)
            info['file_count'] = len(files)
            info['csv_files'] = [f.name for f in csv_files]
            
            # Try to load metadata
            metadata_path = dataset_dir / "metadata.json"
            if metadata_path.exists():
                with open(metadata_path, 'r') as f:
                    info['metadata'] = json.load(f)
        
        return info