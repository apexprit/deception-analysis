    def __init__(self, config: Optional[AppConfig] = None):
        """Initialize dataset downloader.
        
        Args:
            config: Application configuration
        """
        self.config = config or get_default_config()
        self.data_dir = Path(self.config.project.data_dir)
        self.data_dir.mkdir(parents=True, exist_ok=True)
        
    def list_datasets(self) -> pd.DataFrame:
        """List all available public datasets.
        
        Returns:
            DataFrame with dataset information
        """
        data = []
        for key, dataset in self.PUBLIC_DATASETS.items():
            data.append({
                'id': key,
                'name': dataset.name,
                'description': dataset.description[:100] + '...',
                'size_mb': dataset.size_mb,
                'format': dataset.format,
                'features': ', '.join(dataset.features_available),
                'video': '✓' if dataset.video_available else '✗',
                'audio': '✓' if dataset.audio_available else '✗',
                'labels': '✓' if dataset.labels_available else '✗'
            })
        
        return pd.DataFrame(data)
    
    def download_dataset(self, dataset_id: str, 
                        force_download: bool = False,
                        extract: bool = True) -> Path:
        """Download a dataset by ID.
        
        Args:
            dataset_id: Dataset identifier from PUBLIC_DATASETS
            force_download: Force re-download even if exists
            extract: Extract compressed files
            
        Returns:
            Path to downloaded dataset directory
        """
        if dataset_id not in self.PUBLIC_DATASETS:
            raise ValueError(f"Unknown dataset: {dataset_id}. Available: {list(self.PUBLIC_DATASETS.keys())}")
        
        dataset = self.PUBLIC_DATASETS[dataset_id]
        dataset_dir = self.data_dir / dataset_id
        
        # Handle synthetic dataset specially
        if dataset_id == "synthetic_demo":
            return self._generate_synthetic_dataset(dataset_dir)
        
        # Check if already downloaded
        if dataset_dir.exists() and not force_download:
            print(f"Dataset '{dataset_id}' already exists at {dataset_dir}")
            return dataset_dir
        
        # Create directory
        dataset_dir.mkdir(parents=True, exist_ok=True)
        
        # Download file
        if dataset.url == "local":
            raise ValueError("Local dataset should be handled by _generate_synthetic_dataset")
        
        print(f"Downloading {dataset.name} ({dataset.size_mb} MB)...")
        downloaded_file = self._download_file(dataset.url, dataset_dir)
        
        # Extract if needed
        if extract and dataset.format in ['zip', 'tar', 'tar.gz', 'tgz']:
            print(f"Extracting {downloaded_file.name}...")
            self._extract_file(downloaded_file, dataset_dir)
        
        # Create metadata file
        metadata = {
            'dataset_id': dataset_id,
            'name': dataset.name,
            'description': dataset.description,
            'download_url': dataset.url,
            'download_date': pd.Timestamp.now().isoformat(),
            'size_mb': dataset.size_mb,
            'citation': dataset.citation
        }
        
        metadata_path = dataset_dir / "metadata.json"
        with open(metadata_path, 'w') as f:
            json.dump(metadata, f, indent=2)
        
        print(f"✅ Dataset downloaded to {dataset_dir}")
        return dataset_dir
    
    def _download_file(self, url: str, output_dir: Path) -> Path:
        """Download a file with progress bar.
        
        Args:
            url: File URL
            output_dir: Output directory
            
        Returns:
            Path to downloaded file
        """
        # Extract filename from URL
        parsed = urlparse(url)
        filename = os.path.basename(parsed.path)
        if not filename:
            filename = "downloaded_file"
        
        output_path = output_dir / filename
        
        # Stream download with progress bar
        response = requests.get(url, stream=True)
        response.raise_for_status()
        
        total_size = int(response.headers.get('content-length', 0))
        
        with open(output_path, 'wb') as f, tqdm(
            desc=filename,
            total=total_size,
            unit='B',
            unit_scale=True,
            unit_divisor=1024
        ) as pbar:
            for chunk in response.iter_content(chunk_size=8192):
                f.write(chunk)
                pbar.update(len(chunk))
        
        return output_path
    
    def _extract_file(self, archive_path: Path, output_dir: Path):
        """Extract compressed file.
        
        Args:
            archive_path: Path to archive file
            output_dir: Output directory
        """
        if archive_path.suffix == '.zip':
            with zipfile.ZipFile(archive_path, 'r') as zip_ref:
                zip_ref.extractall(output_dir)
        elif archive_path.suffix in ['.tar', '.tar.gz', '.tgz']:
            mode = 'r:gz' if archive_path.suffix in ['.tar.gz', '.tgz'] else 'r'
            with tarfile.open(archive_path, mode) as tar_ref:
                tar_ref.extractall(output_dir)
        else:
            print(f"Warning: Unknown archive format {archive_path.suffix}, skipping extraction")
    
